use crate::server::app_server::AppHttpServer;
use crate::tests::test_utils::{get_free_port, test_callback_ok, wait_for_server};
use std::time::Duration;
use std::fs;
use reqwest::StatusCode;
use reqwest::multipart;

#[tokio::test]
async fn test_upload_plugin_integration() {
    let temp_dir_base = std::env::temp_dir().join("test_upload_plugin");
    if temp_dir_base.exists() {
        fs::remove_dir_all(&temp_dir_base).unwrap();
    }
    fs::create_dir_all(&temp_dir_base).unwrap();
    let temp_dir = temp_dir_base.canonicalize().unwrap();
    
    let upload_dest = temp_dir.join("uploads");
    fs::create_dir(&upload_dest).unwrap();
    
    // Config: Upload mount and Buffer upload mount
    let config_json = format!(r#"{{
        "verbose": true,
        "mounts": [
            {{
                "type": "upload",
                "path": "/upload",
                "temp_dir": "{}"
            }},
            {{
                "type": "buffer_upload",
                "path": "/buffer-upload"
            }}
        ]
    }}"#, upload_dest.to_string_lossy().replace("\\", "\\\\")); 

    let free_port = get_free_port();
    
    let server_task = tokio::spawn(async move {
        let mut server = AppHttpServer::new(free_port, "127.0.0.1".to_string(), test_callback_ok, &config_json);
        server.start();
        loop {
            tokio::time::sleep(Duration::from_secs(1)).await;
        }
    });

    wait_for_server(free_port).await;
    let base_url = format!("http://127.0.0.1:{}", free_port);
    let client = reqwest::Client::new();

    // 1. Upload Plugin Test
    let form = multipart::Form::new()
        .text("key", "value")
        .part("file", multipart::Part::bytes(b"File Content".to_vec()).file_name("test.txt"));
        
    let resp = client.post(format!("{}/upload", base_url))
        .multipart(form)
        .send().await.unwrap();
        
    assert_eq!(resp.status(), StatusCode::OK);
    // Request falls through to callback which returns "Hello World"
    assert_eq!(resp.text().await.unwrap(), "Hello World");
    
    // Verify file exists
    let files: Vec<_> = fs::read_dir(&upload_dest).unwrap().collect();
    assert!(!files.is_empty(), "Upload directory should contain files");
    // We don't know exact name generated by UploadPlugin (uuid), but we check content if we could find it
    // Actually we can check if any file contains "File Content"
    
    // 2. Buffer Upload Plugin Test
    let form_buffer = multipart::Form::new()
        .text("key", "buffer")
        .part("file", multipart::Part::bytes(b"Buffer Content".to_vec()).file_name("buffer.txt"));

    let resp_buffer = client.post(format!("{}/buffer-upload", base_url))
        .multipart(form_buffer)
        .send().await.unwrap();
        
    assert_eq!(resp_buffer.status(), StatusCode::OK);
    let text = resp_buffer.text().await.unwrap();
    // Request falls through to callback which returns "Hello World"
    assert_eq!(text, "Hello World");

    server_task.abort();
    fs::remove_dir_all(&temp_dir_base).unwrap();
}

/// Task 6 的下游验证：非 ASCII 文件名走**完整链路**
/// （plugin → 收集 header → C 边界 → 回调）后，JS 侧仍能拿到可读的文件名。
///
/// 为什么非要在这一层再测一遍：plugin 层用例断言的是「设进去的值能 `to_str()`」，
/// 而这里断言的是 **JS 实际收到的那份 `headers_json`**。
/// 修复前这里看到的是 `"x-uploaded-original-name": ""`（空串）——
/// 那正是原始 bug 的用户可见症状，也是这条用例的失败形态。
#[tokio::test]
async fn test_upload_non_ascii_filename_reaches_js_readable() {
    let temp_dir_base = std::env::temp_dir().join("test_upload_non_ascii_e2e");
    if temp_dir_base.exists() {
        fs::remove_dir_all(&temp_dir_base).unwrap();
    }
    fs::create_dir_all(&temp_dir_base).unwrap();
    let temp_dir = temp_dir_base.canonicalize().unwrap();

    let upload_dest = temp_dir.join("uploads");
    fs::create_dir(&upload_dest).unwrap();

    let config_json = format!(r#"{{
        "verbose": true,
        "mounts": [
            {{
                "type": "upload",
                "path": "/upload",
                "temp_dir": "{}"
            }},
            {{
                "type": "buffer_upload",
                "path": "/buffer-upload"
            }}
        ]
    }}"#, upload_dest.to_string_lossy().replace("\\", "\\\\"));

    let free_port = get_free_port();

    let server_task = tokio::spawn(async move {
        let mut server = AppHttpServer::new(
            free_port,
            "127.0.0.1".to_string(),
            crate::tests::test_utils::test_callback_echo_headers,
            &config_json,
        );
        server.start();
        loop {
            tokio::time::sleep(Duration::from_secs(1)).await;
        }
    });

    wait_for_server(free_port).await;
    let base_url = format!("http://127.0.0.1:{}", free_port);
    let client = reqwest::Client::new();

    // ---- 1) upload 插件：非 ASCII 文件名 ----
    let form = multipart::Form::new().part(
        "file",
        multipart::Part::bytes(b"File Content".to_vec()).file_name("报告.pdf"),
    );
    let resp = client
        .post(format!("{}/upload", base_url))
        .multipart(form)
        .send()
        .await
        .unwrap();
    assert_eq!(resp.status(), StatusCode::OK);

    // 回调把 JS 侧看到的 headers 原样回显，这里解析它 —— 判据与 JS 完全一致
    let body = resp.text().await.unwrap();
    let headers: std::collections::HashMap<String, String> =
        serde_json::from_str(&body).expect("回调应回显 headers JSON");

    let name = headers
        .get("x-uploaded-original-name")
        .expect("JS 侧必须能看到 x-uploaded-original-name");
    assert_ne!(
        name, "",
        "非 ASCII 文件名被静默置空 —— 这正是 Task 6 要修的 bug"
    );
    assert_eq!(name, "%E6%8A%A5%E5%91%8A.pdf");
    assert_eq!(
        headers.get("x-uploaded-filename-encoding").map(|s| s.as_str()),
        Some("percent"),
        "JS 侧需要标记头才知道要 decode"
    );
    assert_eq!(
        urlencoding::decode(name).unwrap().into_owned(),
        "报告.pdf",
        "percent 解码后应还原原始文件名"
    );

    // 路径头也必须是可读的（非 ASCII 扩展名会破坏它，见 plugin_upload.rs 的对应用例）
    let path = headers
        .get("x-uploaded-file-path")
        .expect("JS 侧必须能看到 x-uploaded-file-path");
    assert_ne!(path, "", "路径头被静默置空");
    assert!(
        std::path::Path::new(path).exists(),
        "路径头指向的文件应真实存在: {}",
        path
    );

    // ---- 2) buffer_upload 插件：非 ASCII 文件名 ----
    let form_buffer = multipart::Form::new().part(
        "file",
        multipart::Part::bytes(b"Buffer Content".to_vec()).file_name("报告.bin"),
    );
    let resp_buffer = client
        .post(format!("{}/buffer-upload", base_url))
        .multipart(form_buffer)
        .send()
        .await
        .unwrap();
    assert_eq!(resp_buffer.status(), StatusCode::OK);

    let body_buffer = resp_buffer.text().await.unwrap();
    let headers_buffer: std::collections::HashMap<String, String> =
        serde_json::from_str(&body_buffer).expect("回调应回显 headers JSON");

    let name_buffer = headers_buffer
        .get("x-upload-filename")
        .expect("JS 侧必须能看到 x-upload-filename");
    assert_ne!(name_buffer, "", "buffer_upload 的文件名被静默置空");
    assert_eq!(name_buffer.as_str(), urlencoding::encode("报告.bin").to_string());
    assert_eq!(
        headers_buffer
            .get("x-upload-filename-encoding")
            .map(|s| s.as_str()),
        Some("percent")
    );

    // ---- 3) 纯 ASCII 必须原样、且不带标记头（向后兼容）----
    let form_ascii = multipart::Form::new().part(
        "file",
        multipart::Part::bytes(b"ASCII Content".to_vec()).file_name("plain.txt"),
    );
    let resp_ascii = client
        .post(format!("{}/upload", base_url))
        .multipart(form_ascii)
        .send()
        .await
        .unwrap();
    let body_ascii = resp_ascii.text().await.unwrap();
    let headers_ascii: std::collections::HashMap<String, String> =
        serde_json::from_str(&body_ascii).expect("回调应回显 headers JSON");
    assert_eq!(
        headers_ascii.get("x-uploaded-original-name").map(|s| s.as_str()),
        Some("plain.txt"),
        "纯 ASCII 文件名必须原样传递"
    );
    assert!(
        headers_ascii.get("x-uploaded-filename-encoding").is_none(),
        "纯 ASCII 时不应出现 encoding 标记头"
    );

    server_task.abort();
    fs::remove_dir_all(&temp_dir_base).unwrap();
}
